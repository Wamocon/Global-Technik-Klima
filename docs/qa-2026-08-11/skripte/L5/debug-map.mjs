import { chromium } from 'file:///D:/01%20Antigrafity%20Projekte/25%20Global-Technik-Klima/node_modules/playwright/index.mjs'
const b = await chromium.launch()
const ctx = await b.newContext()
const page = await ctx.newPage()
const log = []
page.on('request', r => log.push('REQ  ' + r.url().slice(0,70)))
page.on('requestfailed', r => log.push('FAIL ' + r.url().slice(0,70) + ' :: ' + r.failure()?.errorText))
page.on('framenavigated', f => log.push('FRAME ' + f.url().slice(0,70)))
await page.goto('http://localhost:4321/de', { waitUntil: 'networkidle' })
console.log('frames after load:', page.frames().length, page.frames().map(f=>f.url().slice(0,50)))
await page.evaluate(() => document.querySelector('#kontakt').scrollIntoView())
await page.waitForTimeout(4000)
console.log('frames after scroll:', page.frames().length, page.frames().map(f=>f.url().slice(0,50)))
const inPage = await page.evaluate(() => performance.getEntriesByType('resource').map(r=>r.name).filter(n=>!n.includes('localhost')))
console.log('in-page non-localhost resources:', inPage)
const ifr = await page.$eval('.cmap iframe', el => ({ src: el.getAttribute('src').slice(0,60), loading: el.getAttribute('loading'), w: el.clientWidth, h: el.clientHeight, box: el.getBoundingClientRect().top }))
console.log('iframe:', ifr)
console.log('--- events mentioning google ---')
console.log(log.filter(l=>/google/i.test(l)).join('\n') || '(none)')
console.log('--- total events:', log.length, '| failures:', log.filter(l=>l.startsWith('FAIL')).length)
console.log(log.filter(l=>l.startsWith('FAIL')).slice(0,5).join('\n'))
await b.close()
